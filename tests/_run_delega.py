r3 = d3.delega('qualcosa')
t.check('errore', r3.esito == 'errore')
r4 = Figlio('esaurito', '', passi=12, motivo='finito')
t.check('esaurito non ok', not r4.ok)
r5 = Figlio('risposto', '', passi=1)
t.check('vuoto ok', r5.esito == 'risposto')
