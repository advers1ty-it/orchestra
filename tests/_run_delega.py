import sys, os
sys.path.insert(0, '.')
from tests import test_delega as t
from orchestra.delega import Delegatore, Figlio
from tests.test_delega import FiglioFalso
t.PASS, t.FAIL = [], []
f = FiglioFalso('Il file contiene 42 righe.')
